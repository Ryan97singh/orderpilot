"use client";

import { useQuery } from "@tanstack/react-query";
import { ArrowLeft, Ban, Check, Sparkles } from "lucide-react";
import Link from "next/link";
import { useParams } from "next/navigation";
import { useState } from "react";
import { OrderStatusBadge, SourceBadge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardBody, CardHeader } from "@/components/ui/card";
import { ConfirmDialog } from "@/components/ui/confirm-dialog";
import { Alert, ErrorState, LoadingRows, Skeleton } from "@/components/ui/feedback";
import { Markdown } from "@/components/ui/markdown";
import { api } from "@/lib/api";
import { errorMessage } from "@/lib/api-error";
import { useAuth } from "@/lib/auth/auth-context";
import { CHANNEL_LABEL, cn, formatAed, formatDateTime, formatNumber } from "@/lib/format";
import { useOrderAction } from "@/lib/order-mutations";
import { queryKeys } from "@/lib/queries";
import type { SalesOrder } from "@/lib/types";

function OutletCard({ outletId }: { outletId: number }) {
  const { data: outlet, isPending, isError } = useQuery({
    queryKey: queryKeys.outlet(outletId),
    queryFn: ({ signal }) => api.outlets.get(outletId, signal),
  });
  if (isError) return null;
  const available = outlet ? (outlet.availableCredit ?? outlet.creditLimit - outlet.outstandingBalance) : 0;
  const usedPct = outlet ? Math.min(100, (outlet.outstandingBalance / outlet.creditLimit) * 100) : 0;
  return (
    <Card>
      <CardHeader title="Outlet" />
      <CardBody>
        {isPending ? (
          <Skeleton className="h-20" />
        ) : (
          <>
            <p className="font-medium">{outlet.name}</p>
            <p className="text-sm text-muted">
              {outlet.code} · {CHANNEL_LABEL[outlet.channel] ?? outlet.channel} · {outlet.city}
            </p>
            <div className="mt-4">
              <div className="flex justify-between text-xs text-muted">
                <span>Credit used</span>
                <span className="tabular-nums">
                  {formatAed(outlet.outstandingBalance)} / {formatAed(outlet.creditLimit)}
                </span>
              </div>
              <div
                role="meter"
                aria-label="Credit used"
                aria-valuemin={0}
                aria-valuemax={100}
                aria-valuenow={Math.round(usedPct)}
                className="mt-1.5 h-2 overflow-hidden rounded-full bg-surface-muted"
              >
                <div
                  className={cn("h-full rounded-full", usedPct > 90 ? "bg-warning" : "bg-primary")}
                  style={{ width: `${usedPct}%` }}
                />
              </div>
              <p className="mt-1.5 text-sm">
                <span className="text-muted">Available credit: </span>
                <span className="font-medium tabular-nums">{formatAed(available)}</span>
              </p>
            </div>
          </>
        )}
      </CardBody>
    </Card>
  );
}

function SummaryCard({ order }: { order: SalesOrder }) {
  const summarize = useOrderAction("aiSummary");
  return (
    <Card>
      <CardHeader
        title={
          <span className="inline-flex items-center gap-1.5">
            <Sparkles aria-hidden className="size-4 text-primary-text" /> AI summary
          </span>
        }
        description={order.aiSummary ? "Generated by core-api with Spring AI" : "Three key points and a risk note."}
      />
      <CardBody className="flex flex-col gap-3">
        {summarize.isError && <Alert tone="danger">{errorMessage(summarize.error)}</Alert>}
        {summarize.isPending ? (
          <div role="status" className="flex flex-col gap-2">
            <span className="sr-only">Generating summary…</span>
            <Skeleton className="h-4 w-11/12" />
            <Skeleton className="h-4 w-4/5" />
            <Skeleton className="h-4 w-3/4" />
          </div>
        ) : (
          order.aiSummary && <Markdown>{order.aiSummary}</Markdown>
        )}
        <Button
          variant={order.aiSummary ? "secondary" : "primary"}
          onClick={() => summarize.mutate(order.id)}
          loading={summarize.isPending}
          className="self-start"
        >
          <Sparkles aria-hidden className="size-4" /> {order.aiSummary ? "Regenerate" : "Generate AI summary"}
        </Button>
      </CardBody>
    </Card>
  );
}

export default function OrderDetailPage() {
  const params = useParams<{ id: string }>();
  const id = Number(params.id);
  const { isManager } = useAuth();
  const [confirmCancel, setConfirmCancel] = useState(false);
  const approve = useOrderAction("approve");
  const cancel = useOrderAction("cancel");

  const query = useQuery({
    queryKey: queryKeys.order(id),
    queryFn: ({ signal }) => api.orders.get(id, signal),
    enabled: Number.isFinite(id),
  });

  const back = (
    <Link href="/orders" className="mb-4 inline-flex items-center gap-1 text-sm text-muted hover:text-foreground">
      <ArrowLeft aria-hidden className="size-4" /> All orders
    </Link>
  );

  if (query.isPending) {
    return (
      <div className="mx-auto max-w-5xl px-4 py-6 lg:px-8 lg:py-8">
        {back}
        <LoadingRows rows={5} label="Loading order" />
      </div>
    );
  }
  if (query.isError) {
    return (
      <div className="mx-auto max-w-5xl px-4 py-6 lg:px-8 lg:py-8">
        {back}
        <ErrorState error={query.error} onRetry={() => void query.refetch()} title="Couldn't load this order" />
      </div>
    );
  }

  const order = query.data;
  const canApprove = isManager && order.status === "PENDING_APPROVAL";
  const canCancel = order.status === "PENDING_APPROVAL" || order.status === "CONFIRMED";
  const actionError = approve.error ?? cancel.error;

  return (
    <div className="mx-auto max-w-5xl px-4 py-6 lg:px-8 lg:py-8">
      {back}
      <header className="mb-6 flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between">
        <div>
          <div className="flex flex-wrap items-center gap-2">
            <h1 className="font-mono text-xl font-semibold tracking-tight sm:text-2xl">{order.orderNo}</h1>
            <OrderStatusBadge status={order.status} />
            <SourceBadge source={order.source} />
          </div>
          <p className="mt-1 text-sm text-muted">
            Created {formatDateTime(order.createdAt)} by {order.createdBy}
          </p>
        </div>
        {(canApprove || canCancel) && (
          <div className="flex gap-2">
            {canCancel && (
              <Button variant="danger" onClick={() => setConfirmCancel(true)} disabled={approve.isPending}>
                <Ban aria-hidden className="size-4" /> Cancel order
              </Button>
            )}
            {canApprove && (
              <Button onClick={() => approve.mutate(order.id)} loading={approve.isPending} disabled={cancel.isPending}>
                <Check aria-hidden className="size-4" /> Approve
              </Button>
            )}
          </div>
        )}
      </header>

      {actionError && (
        <Alert tone="danger" title="That didn't work" className="mb-4">
          {errorMessage(actionError)}
        </Alert>
      )}
      {order.status === "PENDING_APPROVAL" && !isManager && (
        <Alert tone="warning" title="Waiting for manager approval" className="mb-4">
          This order exceeds the outlet&apos;s credit limit. A sales manager needs to approve it before stock is reserved.
        </Alert>
      )}

      <div className="grid gap-4 lg:grid-cols-[1fr_20rem]">
        <div className="flex min-w-0 flex-col gap-4">
          <Card>
            <CardHeader title="Lines" description={`${order.lines?.length ?? 0} product${order.lines?.length === 1 ? "" : "s"}`} />
            <div className="mt-3 overflow-x-auto">
              <table className="w-full text-sm">
                <caption className="sr-only">Order lines</caption>
                <thead className="text-xs text-muted">
                  <tr className="border-y border-border">
                    <th scope="col" className="px-4 py-2 text-left font-medium sm:px-5">Product</th>
                    <th scope="col" className="px-2 py-2 text-right font-medium">Cases</th>
                    <th scope="col" className="hidden px-2 py-2 text-right font-medium sm:table-cell">Unit</th>
                    <th scope="col" className="hidden px-2 py-2 text-right font-medium sm:table-cell">Disc.</th>
                    <th scope="col" className="px-4 py-2 text-right font-medium sm:px-5">Total</th>
                  </tr>
                </thead>
                <tbody>
                  {order.lines?.map((line) => (
                    <tr key={line.sku} className="border-b border-border last:border-0">
                      <td className="px-4 py-2.5 sm:px-5">
                        <p className="font-medium">{line.productName}</p>
                        <p className="font-mono text-xs text-muted">{line.sku}</p>
                      </td>
                      <td className="px-2 py-2.5 text-right tabular-nums">{formatNumber(line.qtyCases)}</td>
                      <td className="hidden px-2 py-2.5 text-right tabular-nums sm:table-cell">{formatAed(line.unitPrice)}</td>
                      <td className="hidden px-2 py-2.5 text-right tabular-nums sm:table-cell">
                        {line.discountPct ? <span className="text-success">−{line.discountPct}%</span> : "—"}
                      </td>
                      <td className="px-4 py-2.5 text-right font-medium tabular-nums sm:px-5">{formatAed(line.lineTotal)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <dl className="grid grid-cols-2 gap-y-1 border-t border-border px-4 py-4 text-sm sm:px-5">
              <dt className="text-muted">Subtotal</dt>
              <dd className="text-right tabular-nums">{formatAed(order.subtotal)}</dd>
              <dt className="text-muted">Promotions</dt>
              <dd className="text-right text-success tabular-nums">−{formatAed(order.discount)}</dd>
              <dt className="font-semibold">Total</dt>
              <dd className="text-right text-base font-semibold tabular-nums">{formatAed(order.total)}</dd>
            </dl>
          </Card>
          {order.notes && (
            <Card>
              <CardHeader title="Notes" />
              <CardBody className="text-sm whitespace-pre-wrap">{order.notes}</CardBody>
            </Card>
          )}
        </div>

        <div className="flex flex-col gap-4">
          <SummaryCard order={order} />
          <OutletCard outletId={order.outletId} />
        </div>
      </div>

      <ConfirmDialog
        open={confirmCancel}
        title={`Cancel ${order.orderNo}?`}
        confirmLabel="Cancel order"
        tone="danger"
        loading={cancel.isPending}
        onClose={() => setConfirmCancel(false)}
        onConfirm={() => cancel.mutate(order.id, { onSettled: () => setConfirmCancel(false) })}
      >
        Any reserved stock is released back to the warehouse. This can&apos;t be undone.
      </ConfirmDialog>
    </div>
  );
}
